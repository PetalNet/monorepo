// Generates test/all.dart, which runs every `*_test.dart` suite in ONE isolate.
//
// `flutter test` compiles and boots a separate isolate per test file; with this
// package's suites that dominates wall time (flutter/flutter#90225). CI runs
// `flutter test test/all.dart`; locally, per-file runs (`flutter test
// test/foo_test.dart`) and a bare `flutter test` keep working because the
// aggregate is not named `*_test.dart`.
//
//   dart run tool/gen_all_test.dart          rewrite test/all.dart
//   dart run tool/gen_all_test.dart --check  exit 1 if it is out of date
import 'dart:io';

const _header = '''
// GENERATED by tool/gen_all_test.dart; do not edit. Run
// `dart run tool/gen_all_test.dart` after adding or removing a test file.
//
// Runs every suite in one isolate. Suites must not leak global state: reset
// anything a suite mutates in its own tearDown, and make one-time setup
// (e.g. RustLib.init) idempotent.
''';

void main(List<String> args) {
  final appDir = File.fromUri(Platform.script).parent.parent;
  final testDir = Directory.fromUri(appDir.uri.resolve('test/'));
  final out = File.fromUri(testDir.uri.resolve('all.dart'));

  final suites =
      testDir
          .listSync(recursive: true)
          .whereType<File>()
          .map((f) => f.uri.path.substring(testDir.uri.path.length))
          .where((p) => p.endsWith('_test.dart'))
          .toList()
        ..sort();

  final mainDecl = RegExp(r'^void main\(\) \{', multiLine: true);
  for (final path in suites) {
    final src = File.fromUri(testDir.uri.resolve(path)).readAsStringSync();
    if (!mainDecl.hasMatch(src)) {
      stderr.writeln(
        'test/$path: main must be `void main() {` (a synchronous main) so '
        'it can run inside a group.',
      );
      exit(1);
    }
  }

  final buf = StringBuffer(_header)..writeln();
  for (final path in suites) {
    buf.writeln("import '$path' as ${_alias(path)};");
  }
  buf
    ..writeln()
    ..writeln('void main() {');
  for (final path in suites) {
    buf.writeln("  group('$path', ${_alias(path)}.main);");
  }
  buf.writeln('}');
  final generated = buf.toString().replaceFirst(
    '\nimport ',
    "\nimport 'package:flutter_test/flutter_test.dart';\nimport ",
  );

  if (args.contains('--check')) {
    final current = out.existsSync() ? out.readAsStringSync() : '';
    if (current != generated) {
      stderr.writeln(
        'test/all.dart is out of date. Run '
        '`dart run tool/gen_all_test.dart` in apps/point/app and commit it.',
      );
      exit(1);
    }
    return;
  }
  out.writeAsStringSync(generated);
  stdout.writeln('test/all.dart: ${suites.length} suites');
}

String _alias(String path) => path
    .replaceAll(RegExp(r'\.dart$'), '')
    .replaceAll(RegExp('[^A-Za-z0-9]+'), '_');
